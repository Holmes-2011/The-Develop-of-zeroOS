#ifndef CONFIRM_H
#define CONFIRM_H

/* 内核绘制的确认框（v0.13）。

   这是整个权限模型里最关键的一块：模型（不管跑在宿主机还是用户态）只能"申请确认"，
   答案只从物理键盘来。模型输出的文字再怎么写"用户已同意"，也到不了这里。

   两条防线：
     1. 问之前先清空键盘缓冲区——之前敲进去还没处理的按键（不管是人提前按的，
        还是以后别的路径塞进来的）一律作废，并在框里注明丢了几个。
     2. 只认 y / n；别的键一概忽略；超时按"拒绝"处理。

   框通过 console 输出，所以屏幕和串口都看得到（串口给自动测试看）；
   但串口没有输入，答案只能来自键盘。 */

#define CONFIRM_TIMEOUT_MS 20000

/* 返回 1 = 允许，0 = 拒绝，-1 = 超时 */
int confirm_ask(const char *action, const char *detail);

#endif
